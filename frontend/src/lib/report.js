// Builds the plain-text and printable versions of a meeting report.
// Kept free of imports so it can be reused and tested on its own.

const dateFormat = new Intl.DateTimeFormat(undefined, { dateStyle: 'long', timeStyle: 'short' })

function when(iso) {
  return iso ? dateFormat.format(new Date(iso)) : ''
}

function taskLine(t) {
  const details = [t.assignee ? `Owner: ${t.assignee}` : 'Owner: not assigned']
  if (t.deadline) details.push(`Due: ${t.deadline}`)
  return `${t.title} (${details.join(', ')})`
}

export function reportText(meeting, { includeTranscript = false } = {}) {
  const lines = [meeting.title, when(meeting.createdAt), '', 'Summary', meeting.summary || 'No summary.', '']

  lines.push('Decisions')
  if (meeting.decisions.length === 0) lines.push('No decisions recorded.')
  meeting.decisions.forEach((d) => lines.push(`- ${d.text}`))
  lines.push('')

  lines.push('Action items')
  if (meeting.tasks.length === 0) lines.push('No action items.')
  meeting.tasks.forEach((t) => lines.push(`[${t.status === 'DONE' ? 'x' : ' '}] ${taskLine(t)}`))

  if (includeTranscript) lines.push('', 'Transcript', meeting.transcript)
  return lines.join('\n')
}

function esc(value) {
  return String(value ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c])
}

export function reportHtml(meeting, { includeTranscript = false } = {}) {
  const decisions = meeting.decisions.length
    ? `<ul>${meeting.decisions.map((d) => `<li>${esc(d.text)}</li>`).join('')}</ul>`
    : '<p class="muted">No decisions recorded.</p>'

  const tasks = meeting.tasks.length
    ? `<ul class="tasks">${meeting.tasks
        .map((t) => {
          const done = t.status === 'DONE'
          return `<li class="${done ? 'done' : ''}"><span class="box">${done ? '&#9745;' : '&#9744;'}</span><span>${esc(taskLine(t))}</span></li>`
        })
        .join('')}</ul>`
    : '<p class="muted">No action items.</p>'

  const transcript = includeTranscript
    ? `<h2>Transcript</h2><p class="transcript">${esc(meeting.transcript)}</p>`
    : ''

  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>${esc(meeting.title)}</title>
<style>
  @page { margin: 18mm; }
  body { font-family: "Segoe UI", system-ui, -apple-system, Arial, sans-serif; color: #1c1912; line-height: 1.55; font-size: 11pt; }
  h1 { font-size: 20pt; margin: 0 0 2pt; }
  h2 { font-size: 13pt; margin: 18pt 0 6pt; border-bottom: 1px solid #d8ccb4; padding-bottom: 3pt; }
  .meta, .muted, .footer { color: #5d5444; }
  .meta { margin: 0 0 6pt; }
  ul { margin: 0; padding-left: 18pt; }
  li { margin: 3pt 0; }
  ul.tasks { list-style: none; padding-left: 0; }
  ul.tasks li { display: flex; gap: 8pt; }
  ul.tasks li.done span:last-child { text-decoration: line-through; color: #5d5444; }
  .box { font-size: 13pt; line-height: 1.2; }
  .transcript { white-space: pre-wrap; font-size: 10pt; }
  .footer { margin-top: 24pt; font-size: 9pt; border-top: 1px solid #d8ccb4; padding-top: 6pt; }
</style></head>
<body>
  <h1>${esc(meeting.title)}</h1>
  <p class="meta">${esc(when(meeting.createdAt))}</p>
  <h2>Summary</h2>
  <p>${esc(meeting.summary || 'No summary.')}</p>
  <h2>Decisions</h2>
  ${decisions}
  <h2>Action items</h2>
  ${tasks}
  ${transcript}
  <p class="footer">Generated by DevMeetScribe AI. The summary, decisions and tasks were produced by an AI model and may contain mistakes.</p>
</body></html>`
}

/** Opens the browser print dialog for the report. Choose "Save as PDF" as the destination. */
export function printReport(meeting, options) {
  const frame = document.createElement('iframe')
  frame.setAttribute('aria-hidden', 'true')
  frame.style.cssText = 'position:fixed;right:0;bottom:0;width:0;height:0;border:0;'
  document.body.appendChild(frame)

  const win = frame.contentWindow
  win.document.open()
  win.document.write(reportHtml(meeting, options))
  win.document.close()

  const cleanup = () => frame.remove()
  win.addEventListener('afterprint', () => setTimeout(cleanup, 500))
  setTimeout(cleanup, 120000)
  setTimeout(() => {
    win.focus()
    win.print()
  }, 250)
}
